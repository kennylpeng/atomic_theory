#!/usr/bin/env python3
"""Render the final color-example table from external sources.json selections.

Frozen example selections and artwork files are inputs, not shipped code.
--font regenerates Unicode text PDF snippets using an explicitly supplied font.
Without --font, the corresponding previously rendered snippets must exist.
"""
from __future__ import annotations
from project_paths import resource_path as _paper_path, resource_location as _paper_location

import argparse
import json
import math
from pathlib import Path
import textwrap


def escape(text):
    special = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
               "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}
    return "".join(special.get(c, c) for c in text)


def snippet(text, path, font):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.font_manager import FontProperties
    from matplotlib.ft2font import FT2Font
    face = FT2Font(str(font))
    missing = {c for c in text if not c.isspace() and face.get_char_index(ord(c)) == 0}
    if missing:
        raise ValueError(f"Font {font} lacks glyphs: {''.join(sorted(missing))}")
    fig = plt.figure(figsize=(10, .3))
    fig.text(0, .5, text, fontproperties=FontProperties(fname=str(font)), fontsize=10, va="center")
    fig.savefig(path, bbox_inches="tight", pad_inches=.005, transparent=True)
    plt.close(fig)


HEADER = r"""% Generated by experiments/colors/render_color_examples_table.py.
\begin{table*}[p]
\centering
\providecommand{\ColorExamplesPath}{gemini_color_feature_examples_table}
\providecommand{\ColorExamplesMaxHeight}{0.80\textheight}
\ifdefined\ColorExamplesBox\else\newsavebox{\ColorExamplesBox}\fi
\begingroup
\begin{lrbox}{\ColorExamplesBox}%
\begin{minipage}{\linewidth}
\setlength{\parindent}{0pt}
\scriptsize
\setlength{\tabcolsep}{0pt}
\renewcommand{\arraystretch}{1}
\begin{tabular}{@{}ll*{5}{c}@{}}
& \textbf{top activating texts} & \multicolumn{5}{c}{\textbf{top activating artwork}} \\[2mm]
"""
FOOTER = r"""\end{tabular}
\end{minipage}%
\end{lrbox}%
\noindent\makebox[\linewidth][c]{%
  \ifdim\dimexpr\ht\ColorExamplesBox+\dp\ColorExamplesBox\relax>\ColorExamplesMaxHeight\relax
    \resizebox*{!}{\ColorExamplesMaxHeight}{\usebox{\ColorExamplesBox}}%
  \else
    \usebox{\ColorExamplesBox}%
  \fi
}%
\endgroup
\par
\caption{Top-activating text and image examples for eight color-selective
features in the Gemini 131K sparse autoencoder. Each row shows the five
highest-activating distinct general-corpus texts and five highest-activating
WikiArt images for one feature, ordered by decreasing activation within
each corpus. Parentheses give raw post-TopK activations. Texts are
truncated for display.}
\label{tab:gemini-color-examples}
\end{table*}
"""


def render(sources, output, assets, font=None):
    data = json.loads(sources.read_text())
    features = data["features"]
    if len(features) != 8 or len({f["feature_id"] for f in features}) != 8:
        raise ValueError("Expected eight distinct selected color features")
    rows = []
    assets = assets.resolve()
    for feature in features:
        fid = int(feature["feature_id"])
        for name in ["texts", "wikiart"]:
            records = feature[name]
            values = [float(r["activation"]) for r in records]
            if len(records) != 5 or any(not math.isfinite(v) or v <= 0 for v in values) or values != sorted(values, reverse=True):
                raise ValueError(f"Expected five positive, descending {name} activations for f{fid}")
        if len({r['text'] for r in feature['texts']}) != 5:
            raise ValueError(f"Duplicate full text for f{fid}")
        text_lines = []
        for rank, example in enumerate(feature["texts"], 1):
            excerpt = textwrap.shorten(" ".join(example["text"].split()), width=87, placeholder="...")
            if any(ord(c) > 0x024F for c in excerpt):
                name = f"text_f{fid}_{rank:02d}.pdf"
                if font:
                    snippet(excerpt, assets / name, font)
                if not (assets / name).is_file():
                    raise FileNotFoundError(f"Supply --font or an existing Unicode snippet: {assets / name}")
                value = r"\raisebox{-0.2ex}{\includegraphics[height=1.5ex]{\ColorExamplesPath/" + name + "}}"
            else:
                value = escape(excerpt)
            text_lines.append(value + f" ({example['activation']:.4f})")
        cells = [r"\parbox[c]{0.07\linewidth}{\hspace*{-2mm}\textbf{f" + str(fid) + "}}",
                 r"\parbox[c]{0.27\linewidth}{\raggedright " + "\n\\par\\vspace{1pt}\n".join(text_lines) + "}"]
        for art in feature["wikiart"]:
            name = art["image_path"]
            if _paper_path(name).name != name or not (assets / name).is_file():
                raise FileNotFoundError(f"Missing local artwork file: {name}")
            cells.append(r"\parbox[c]{0.132\linewidth}{\centering" + "\n" +
                r"\includegraphics[width=0.96\linewidth,height=0.80\linewidth,keepaspectratio]{\ColorExamplesPath/" + name + "}\n" +
                r"\par\vspace{1pt} " + f"({art['activation']:.4f})" + "}")
        rows.append(" &\n".join(cells) + r" \\[1mm]")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(HEADER + "\n\n".join(rows) + "\n" + FOOTER)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sources", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--asset-dir", type=Path)
    parser.add_argument("--font", type=Path)
    args = parser.parse_args()
    render(args.sources, args.output, args.asset_dir or args.sources.parent, args.font)
    print(f"Wrote {args.output}: 8 features, 40 texts, 40 artwork examples")


if __name__ == "__main__":
    main()
